-- Flyway 가 애플리케이션 시작 시 한 번만 실행하고, 실행 이력은 flyway_schema_history 테이블에 남는다.
-- 이미 적용된 파일은 절대 수정하지 않는다. 변경이 필요하면 V2__*.sql 을 새로 추가한다.
